/**
 * ASK "COZMC" end-to-end demonstration. ALL DATA HERE IS TEST DATA (fixture car, example.com sources).
 * Run: npm run demo:ask  → also writes docs/ASK_COZMC_DEMO.md with the transcript.
 */
import { describe, expect, it } from 'vitest';
import { writeFileSync } from 'node:fs';
import { ask, type AskDeps, type AskResult } from '../../src/lib/ask/engine';
import { entryDoc } from '../../src/lib/ask/docs';
import { approve, listQueue, getHistory, undo, type QueueItem } from '../../src/lib/ask/queue';
import { MemoryStore } from '../../src/lib/ask/store';
import { TestResearcher, type Findings } from '../../src/lib/ask/research';

const TEST_ENTRY = {
  id: 'gta-vi:entry:test-fixture-comet', gameId: 'gta-vi', slug: 'test-fixture-comet', category: 'vehicles',
  title: 'TEST DATA: Fixture Comet (rare car)', summary: 'TEST DATA. A fictional rare car used only to demonstrate ASK "COZMC".',
  steps: ['TEST DATA: drive to the Fixture Marina garage.'], facts: [{ label: 'Location', value: 'TEST DATA: Fixture Marina garage' }],
  chapter: null, mode: 'story' as const, spoilerLevel: 'none' as const, details: null, verification: 'confirmed' as const,
  sources: [{ publisher: 'TEST source', title: 'Test fixture page', url: 'https://example.com/test-fixture-comet', checkedAt: '2026-11-24' }],
  platformNote: null, gameVersion: null, mapPinIds: [], objectiveIds: [], status: 'published' as const,
};

const DISAGREE: Findings = {
  answer: 'TEST DATA: outside sources disagree on whether the Fixture Comet stays after the mission.',
  spoilerDetail: 'TEST DATA: the car is taken during the "Fixture Heist" mission.', spoilerLevel: 'minor',
  reports: [{ claim: 'TEST DATA: you keep it in your garage', sources: [0] }, { claim: 'TEST DATA: it is lost when the mission ends', sources: [1] }],
  disagreements: ['TEST DATA: Example Guide Site says you keep the car; Example Creator\'s video shows it disappearing after the mission.'],
  uncertain: ['TEST DATA: neither source says which game version they tested.'],
  sources: [
    { publisher: 'Example Guide Site (TEST)', title: 'Fixture Comet guide (TEST)', url: 'https://example.com/guide-a', checkedAt: '2026-11-24', kind: 'guide' },
    { publisher: 'YouTube', title: 'Fixture Comet walkthrough (TEST)', url: 'https://example.com/video-b', checkedAt: '2026-11-24', creator: 'Example Creator (TEST)', kind: 'creator' },
  ],
  proposed: { title: 'TEST DATA: Fixture Comet (rare car)', summary: 'TEST DATA. A fictional rare car used only to demonstrate ASK "COZMC".', steps: ['TEST DATA: drive to the Fixture Marina garage.'], facts: [{ label: 'Location', value: 'TEST DATA: Fixture Marina garage' }, { label: 'After the mission', value: 'Unconfirmed: sources disagree' }], category: 'vehicles' },
  platform: null, patch: null,
};

function deps(store: MemoryStore, researcher: TestResearcher | null, now: string): AskDeps {
  return {
    store, researcher, now: new Date(now),
    docs: [entryDoc(TEST_ENTRY, 'Rare vehicles')], sectionLabels: { vehicles: 'Rare vehicles' },
    config: { limits: { questionsPerVisitorPerDay: 40, webSearchesPerDay: 300, maxWebSearchesPerQuestion: 3, answerCacheHours: 72 } },
    community: { label: 'Ask in the COZMC Discord', href: 'https://discord.gg/VBeBE7MSSq' },
  };
}

const log: string[] = ['# ASK "COZMC" demonstration (TEST DATA)', '', 'Generated by `npm run demo:ask`. Every car, source and URL below is test data.', ''];
const show = (title: string, q: string, r: AskResult) => {
  log.push(`## ${title}`, '', `**Player asks:** "${q}"`, '', `- Status: \`${r.status}\``, `- Our guide: ${r.guide.text || '(nothing)'} [${r.guide.coverage}]`);
  if (r.guide.actions.length) log.push(`- Actions: ${r.guide.actions.map((a) => a.label).join(', ')}`);
  if (r.outside) {
    log.push(`- Outside sources${r.outside.cached ? ' (reused from a recent answer)' : ''}: ${r.outside.answer}`);
    for (const d of r.outside.disagreements) log.push(`  - Disagreement: ${d}`);
    for (const u of r.outside.uncertain) log.push(`  - Still uncertain: ${u}`);
    log.push(`  - Sources: ${r.outside.sources.map((s) => `${s.publisher}${s.creator ? ` (${s.creator})` : ''} <${s.url}>`).join('; ')}`);
    if (r.outsideSpoilerHidden) log.push('  - A spoiler detail is hidden behind "Reveal" for this player.');
  }
  for (const n of r.notes) log.push(`- Note: ${n}`);
  if (r.recorded) log.push(`- Guide Updates queue: item \`${r.recorded.itemId}\`, asked ${r.recorded.count}×`);
  if (r.community) log.push(`- Offered: ${r.community.label}`);
  log.push('');
};

describe('ASK "COZMC" rare-car demo (TEST DATA)', () => {
  const store = new MemoryStore();
  const researcher = new TestResearcher({ 'fixture comet': DISAGREE });

  it('1. our guide already has the answer: no outside search, nothing queued', async () => {
    const q = 'Where can I find the Fixture Comet?';
    const r = await ask(q, 'safe', 'player-1', deps(store, researcher, '2026-11-24T10:00:00Z'));
    show('1. The guide already has the answer', q, r);
    expect(r.status).toBe('guide');
    expect(r.guide.text).toContain('Fixture Marina garage');
    expect(researcher.calls).toBe(0);
    expect(r.recorded).toBeNull();
  });

  it('2. two outside sources disagree: both shown, disagreement explained, spoiler hidden, item queued', async () => {
    const q = 'Can I keep the Fixture Comet after the mission?';
    const r = await ask(q, 'safe', 'player-2', deps(store, researcher, '2026-11-24T10:05:00Z'));
    show('2. Two outside sources disagree', q, r);
    expect(r.status).toBe('guide+outside');
    expect(r.guide.coverage).toBe('partial');
    expect(r.outside!.disagreements).toHaveLength(1);
    expect(r.outsideSpoilerHidden).toBe(true);
    expect(r.community?.href).toContain('discord.gg');
    const [item] = await listQueue(store);
    expect(item!.needsVerification.join(' ')).toMatch(/Sources disagree/);
    expect(item!.affected!.id).toBe('gta-vi:entry:test-fixture-comet');
  });

  it('3. several players ask about the same missing detail: one item, count rises, research reused', async () => {
    for (const [i, q] of ['Do I lose the Fixture Comet after the mission?', 'Will the Fixture Comet stay after the mission?'].entries()) {
      const r = await ask(q, 'safe', `player-${3 + i}`, deps(store, researcher, `2026-11-24T10:1${i}:00Z`));
      show(`3${'ab'[i]}. Another player asks the same thing`, q, r);
      expect(r.outside!.cached).toBe(true);
    }
    expect(researcher.calls).toBe(1);
    const items = await listQueue(store);
    expect(items).toHaveLength(1);
    expect(items[0]!.count).toBe(3);
    expect(items[0]!.findings!.disagreements).toHaveLength(1); // popularity never makes it "verified"
    log.push(`## Queue after three players`, '', `One item, asked ${items[0]!.count}×, top of the review list. Still needs verification: ${items[0]!.needsVerification.join(' | ')}`, '');
  });

  it('4. founder approves a corrected entry: the next player gets the answer straight from our guide', async () => {
    const [item] = await listQueue(store);
    const corrected = { ...(item!.draft as typeof TEST_ENTRY),
      facts: [{ label: 'Location', value: 'TEST DATA: Fixture Marina garage' }, { label: 'After the mission', value: 'TEST DATA: You keep it. Verified in gameplay by the editor.' }],
      verification: 'confirmed' as const, spoilerLevel: 'minor' as const, details: { summary: 'TEST DATA: the car is taken during the "Fixture Heist" mission, then returned.', steps: [] } };
    const res = await approve(store, item!.id, corrected, new Date('2026-11-24T11:00:00Z'));
    expect(res.ok).toBe(true);
    log.push('## Founder approves the correction', '', 'Edited draft: "After the mission: You keep it. Verified in gameplay by the editor." (verification set to confirmed after checking).', '');
    const q = 'Can I keep the Fixture Comet after the mission?';
    const before = researcher.calls;
    const r = await ask(q, 'safe', 'player-6', deps(store, researcher, '2026-11-24T11:05:00Z'));
    show('4. The next player gets the corrected answer from our site', q, r);
    expect(r.status).toBe('guide');
    expect(r.guide.text).toContain('You keep it');
    expect(researcher.calls).toBe(before);
    expect(r.guide.spoilerGate).toEqual({ id: 'gta-vi:entry:test-fixture-comet', level: 'minor' }); // the mission name stays behind "Reveal"
  });

  it('5. undo restores the previous entry and reopens the item; the entry id (and players\' ticks) never change', async () => {
    const h = await getHistory(store);
    expect(await undo(store, h[0]!.id, new Date('2026-11-24T12:00:00Z'))).toBe(true);
    const r = await ask('Can I keep the Fixture Comet after the mission?', 'safe', 'player-7', deps(store, researcher, '2026-11-24T12:05:00Z'));
    expect(r.guide.coverage).toBe('partial');
    const [item] = await listQueue(store);
    expect(item!.status).toBe('open');
    log.push('## Undo', '', `Undo of ${h[0]!.id} restored the previous entry; the item is open again and the guide is back to a partial answer. Entry id unchanged: \`gta-vi:entry:test-fixture-comet\`.`, '');
    writeFileSync('docs/ASK_COZMC_DEMO.md', log.join('\n'));
  });

  it('grouping: "where" and "keep" questions about the same car are separate items', async () => {
    const s = new MemoryStore();
    const d = deps(s, null, '2026-11-24T10:00:00Z');
    d.docs = []; // empty guide: everything is a gap
    await ask('Where does the Fixture Viper spawn?', 'safe', 'a', d);
    await ask('Where can I find the Fixture Viper?', 'safe', 'b', d);
    await ask('Can I keep the Fixture Viper after the mission?', 'safe', 'c', d);
    const items: QueueItem[] = await listQueue(s);
    expect(items.map((i) => [i.clusterKey, i.count])).toEqual([['location:fixture-viper', 2], ['keep:fixture-viper', 1]]);
  });

  it('without live search the guide still answers and the question is still recorded', async () => {
    const s = new MemoryStore();
    const r = await ask('Can I keep the Fixture Comet after the mission?', 'safe', 'p', deps(s, null, '2026-11-24T10:00:00Z'));
    expect(r.status).toBe('unanswered');
    expect(r.guide.coverage).toBe('partial');
    expect(r.notes.join(' ')).toMatch(/Live web search is switched off/);
    expect((await listQueue(s))[0]!.count).toBe(1);
  });

  it('usage limits: over the daily limit the answer is guide-only and still recorded', async () => {
    const s = new MemoryStore();
    const d = deps(s, new TestResearcher({ 'fixture comet': DISAGREE }), '2026-11-24T10:00:00Z');
    d.config.limits.webSearchesPerDay = 2; // less than one question's budget
    const r = await ask('Can I keep the Fixture Comet after the mission?', 'safe', 'p', d);
    expect(r.outside).toBeNull();
    expect(r.notes.join(' ')).toMatch(/limit/);
    expect(r.recorded).not.toBeNull();
  });
});
